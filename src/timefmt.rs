//! Minimal UTC timestamp formatting.
//!
//! Pulling in a full date-time crate for one label is not worth it, so this
//! uses Howard Hinnant's `civil_from_days` algorithm. All timestamps shown in
//! the UI are UTC; there is no timezone database involved.

/// Format a Unix timestamp (milliseconds) as `YYYY-MM-DD HH:MM` in UTC.
pub fn format_utc(ms: u64) -> String {
    let total_seconds = ms / 1000;
    let days = (total_seconds / 86_400) as i64;
    let rem = total_seconds % 86_400;
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02} {:02}:{:02}",
        rem / 3600,
        (rem % 3600) / 60
    )
}

fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let day_of_era = (z - era * 146_097) as u64; // [0, 146096]
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365; // [0, 399]
    let year = year_of_era as i64 + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let mp = (5 * day_of_year + 2) / 153; // [0, 11]
    let day = (day_of_year - (153 * mp + 2) / 5 + 1) as u32; // [1, 31]
    let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32; // [1, 12]
    (if month <= 2 { year + 1 } else { year }, month, day)
}

